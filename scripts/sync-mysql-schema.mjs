// Regenerates prisma/mysql/schema.prisma from the PostgreSQL source of truth.
// The schema body is engine-neutral by convention, so only the header changes.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(resolve(root, "prisma/schema.prisma"), "utf8");

const header = `// GENERATED by scripts/sync-mysql-schema.mjs from prisma/schema.prisma — do not edit by hand.\n`;
let mysql = source
  .replace(/^\/\/ PostgreSQL schema[\s\S]*?\n\n/, header + "\n")
  .replace('provider = "postgresql"', 'provider = "mysql"')
  .replace('output   = "../src/generated/prisma"', 'output   = "../../src/generated/prisma"');

if (!mysql.includes('provider = "mysql"')) {
  throw new Error("Could not switch datasource provider; check prisma/schema.prisma");
}

const target = resolve(root, "prisma/mysql/schema.prisma");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, mysql);
console.log("Wrote", target);
